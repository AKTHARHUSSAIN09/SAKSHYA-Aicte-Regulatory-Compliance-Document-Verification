from typing import Dict, Any, List, Tuple
import fitz  # PyMuPDF
from datetime import datetime

SUSPICIOUS_SOFTWARE_SIGNATURES = [
    "canva",
    "photoshop",
    "adobe illustrator",
    "gimp",
    "inkscape",
    "coreldraw",
    "paint.net",
    "ilovepdf",
    "smallpdf",
    "sejda"
]

class PDFMetadataForensics:
    """
    Analyzes PDF object streams, metadata dictionary, and font alterations
    to detect document forgery, tampering software traces, and chronological impossibilities.
    """
    def __init__(self):
        pass

    def analyze_pdf_bytes(self, pdf_bytes: bytes) -> Tuple[float, List[Dict[str, Any]], Dict[str, Any]]:
        findings: List[Dict[str, Any]] = []
        score = 0.0

        try:
            doc = fitz.open(stream=pdf_bytes, filetype="pdf")
        except Exception as e:
            return 1.0, [{
                "title": "Corrupt or Malformed PDF Stream",
                "severity": "CRITICAL",
                "risk_score": 1.0,
                "description": f"Failed to parse PDF object stream: {str(e)}"
            }], {}

        meta = doc.metadata or {}
        creator = (meta.get("creator") or "").lower()
        producer = (meta.get("producer") or "").lower()
        author = meta.get("author") or ""
        creation_date = meta.get("creationDate") or ""
        mod_date = meta.get("modDate") or ""
        page_count = doc.page_count

        # 1. Suspicious Editing Software Footprint
        detected_software = []
        for s in SUSPICIOUS_SOFTWARE_SIGNATURES:
            if s in creator or s in producer:
                detected_software.append(s)

        if detected_software:
            score += 0.65
            findings.append({
                "title": "Graphic Design / Photo Editing Software Signature Detected",
                "severity": "CRITICAL",
                "risk_score": 0.85,
                "description": (
                    f"Document contains metadata signatures associated with graphic manipulation software: "
                    f"[{', '.join(detected_software).title()}]. Official statutory government certificates (e.g., Fire NOC, "
                    f"Land Deeds) are generated by state IT systems or certified CAD scanners, not graphic design tools."
                ),
                "technical_details": {
                    "creator": meta.get("creator"),
                    "producer": meta.get("producer"),
                    "detected_keywords": detected_software
                }
            })

        # 2. Date Inconsistency: ModDate < CreationDate
        # PDF date format is typically D:YYYYMMDDHHmmSS...
        parsed_creation = self._parse_pdf_date(creation_date)
        parsed_mod = self._parse_pdf_date(mod_date)

        if parsed_creation and parsed_mod:
            if parsed_mod < parsed_creation:
                score += 0.5
                findings.append({
                    "title": "Chronological Timestamp Anomaly in Object Header",
                    "severity": "HIGH",
                    "risk_score": 0.75,
                    "description": (
                        f"PDF Modification Date ({parsed_mod.isoformat()}) chronologically precedes "
                        f"its Creation Date ({parsed_creation.isoformat()}). This is a strong indicator of manual "
                        f"hex editing or timestamp tampering."
                    ),
                    "technical_details": {
                        "creation_date_raw": creation_date,
                        "mod_date_raw": mod_date,
                        "creation_parsed": str(parsed_creation),
                        "mod_parsed": str(parsed_mod)
                    }
                })

        # 3. Multiple Incremental Updates / Font injections
        font_count = 0
        for page in doc:
            fonts = page.get_fonts()
            font_count += len(fonts)

        metadata_summary = {
            "title": meta.get("title", ""),
            "author": author,
            "creator": meta.get("creator", ""),
            "producer": meta.get("producer", ""),
            "creation_date": creation_date,
            "modification_date": mod_date,
            "page_count": page_count,
            "font_references_count": font_count,
            "is_encrypted": doc.is_encrypted
        }

        total_score = min(round(score, 2), 1.0)
        return total_score, findings, metadata_summary

    def _parse_pdf_date(self, d_str: str) -> Any:
        if not d_str:
            return None
        clean = d_str.replace("D:", "").replace("'", "")
        # Try parsing YYYYMMDD
        try:
            if len(clean) >= 8:
                return datetime.strptime(clean[:8], "%Y%m%d")
        except Exception:
            pass
        return None
